#!/usr/bin/env python3
"""
Tests for cage_isomer_builder.utils.rgroup: isomers with several distinct
functional groups (AB, ABC, ...) placed at once.

Every count is checked against brute-force orbit counting on small, closed,
linker-preserving permutation groups (no cage build needed).
"""

import itertools
import random

import numpy as np
import pytest

from cage_isomer_builder.utils import rgroup
from cage_isomer_builder.utils.rgroup import (
    count_rgroup_isomers,
    enumerate_rgroup_isomers,
    identity_fixed_count,
    make_spec,
    prepare_group,
)
from cage_isomer_builder.utils.util import count_unique_isomers_k


def _block_group(n_linkers, fg_per_linker, rng, n_generators, max_order):
    """Closed group generated by random permutations that move whole
    linkers onto whole linkers. Returned without the identity, or None
    as soon as it grows past max_order."""
    n = n_linkers * fg_per_linker
    generators = []
    for _ in range(n_generators):
        linker_perm = list(range(n_linkers))
        rng.shuffle(linker_perm)
        perm = [0] * n
        for linker in range(n_linkers):
            local = list(range(fg_per_linker))
            rng.shuffle(local)
            for i in range(fg_per_linker):
                perm[linker * fg_per_linker + i] = linker_perm[linker] * fg_per_linker + local[i]
        generators.append(tuple(perm))
    identity = tuple(range(n))
    group = {identity}
    frontier = [identity]
    while frontier:
        new = []
        for a in frontier:
            for g in generators:
                b = tuple(g[a[i]] for i in range(n))
                if b not in group:
                    group.add(b)
                    new.append(b)
                    if len(group) > max_order:
                        return None
        frontier = new
    group.discard(identity)
    return [list(p) for p in group]


def _all_configurations(spec):
    """Every labelling allowed by spec (no symmetry), as tuples."""
    F = spec.fg_per_linker
    local = []
    for comp in spec.patterns:
        labels = [0] * (F - sum(comp))
        for c, k in enumerate(comp):
            labels += [c + 1] * k
        local.append(sorted(set(itertools.permutations(labels))))
    ids = [p for p, n in enumerate(spec.pattern_counts) for _ in range(n)]
    for assignment in set(itertools.permutations(ids)):
        for combo in itertools.product(*(local[p] for p in assignment)):
            yield tuple(itertools.chain.from_iterable(combo))


def _orbit(config, group):
    images = {config}
    for g in group:
        image = [0] * len(config)
        for x, label in enumerate(config):
            image[g[x]] = label
        images.add(tuple(image))
    return frozenset(images)


def _brute_orbits(group, spec):
    return {_orbit(config, group) for config in _all_configurations(spec)}


def _cases(seed, n_cases, max_order=400):
    rng = random.Random(seed)
    out = []
    while len(out) < n_cases:
        n_linkers = rng.randint(2, 4)
        fg_per_linker = rng.randint(2, 4)
        group = _block_group(n_linkers, fg_per_linker, rng, rng.randint(1, 2), max_order)
        if group is not None:
            out.append((n_linkers, fg_per_linker, group))
    return out


def _uniform_patterns(fg_per_linker):
    """'A', 'AB', 'AAB', 'ABC', ... that fit on one linker."""
    out = []
    for size in range(fg_per_linker + 1):
        for comp in itertools.combinations_with_replacement('ABC', size):
            out.append(''.join(comp))
    return sorted(set(out))


def test_uniform_mode_matches_brute_force() -> None:
    n_checked = 0
    for n_linkers, F, group in _cases(seed=1, n_cases=25):
        for groups in _uniform_patterns(F):
            spec = make_spec(n_linkers, F, groups)
            expected = len(_brute_orbits(group, spec))
            got = count_rgroup_isomers(group, n_linkers * F, F, groups=groups)
            assert got == expected, (n_linkers, F, groups, got, expected)
            n_checked += 1
    assert n_checked > 100


def test_mixed_mode_matches_brute_force() -> None:
    rng = random.Random(7)
    n_checked = 0
    for n_linkers, F, group in _cases(seed=2, n_cases=25):
        for _ in range(4):
            options = [p for p in _uniform_patterns(F)]
            chosen = rng.sample(options, k=min(len(options), rng.randint(2, 3)))
            counts = [0] * len(chosen)
            for _ in range(n_linkers):
                counts[rng.randrange(len(chosen))] += 1
            patterns = dict(zip(chosen, counts))
            spec = make_spec(n_linkers, F, linker_patterns=patterns)
            expected = len(_brute_orbits(group, spec))
            got = count_rgroup_isomers(group, n_linkers * F, F, linker_patterns=patterns)
            assert got == expected, (n_linkers, F, patterns, got, expected)
            n_checked += 1
    assert n_checked >= 100


def test_enumeration_gives_exactly_one_member_of_every_orbit() -> None:
    for n_linkers, F, group in _cases(seed=3, n_cases=12):
        for kwargs in ({'groups': 'AB'}, {'groups': 'A'},
                       {'linker_patterns': {'A': n_linkers - 1, 'B': 1}},
                       {'linker_patterns': {'AB': 1, '': n_linkers - 1}}):
            if 'groups' in kwargs and len(kwargs['groups']) > F:
                continue
            spec = make_spec(n_linkers, F, **kwargs)
            orbits = _brute_orbits(group, spec)
            isomers = enumerate_rgroup_isomers(group, n_linkers * F, F, **kwargs)
            hit = [next(o for o in orbits if iso.site_labels in o) for iso in isomers]
            assert len(set(hit)) == len(hit) == len(orbits), kwargs


def test_compiled_and_pure_python_agree() -> None:
    n_linkers, F, group = _cases(seed=4, n_cases=1)[0]
    compiled = enumerate_rgroup_isomers(group, n_linkers * F, F, groups='AB')
    original = rgroup._scan
    rgroup._scan = rgroup._scan_py
    try:
        pure = enumerate_rgroup_isomers(group, n_linkers * F, F, groups='AB')
    finally:
        rgroup._scan = original
    assert compiled == pure


def test_single_label_reproduces_existing_k_counts() -> None:
    for n_linkers, F, group in _cases(seed=5, n_cases=15):
        for k in range(F + 1):
            old = count_unique_isomers_k(group, n_linkers, n_linkers * F, F, active_per_linker=k)
            new = count_rgroup_isomers(group, n_linkers * F, F, groups='A' * k)
            assert old == new


def test_identity_count_is_raw_configuration_count() -> None:
    for patterns in ({'AB': 3}, {'A': 2, 'B': 1}, {'ABC': 1, 'A': 1, '': 1}):
        spec = make_spec(3, 4, linker_patterns=patterns)
        assert identity_fixed_count(spec) == sum(1 for _ in _all_configurations(spec))
    # No symmetry: nothing merges.
    assert count_rgroup_isomers([], 12, 4, groups='AB') == 12 ** 3


def test_label_names_and_order_do_not_matter() -> None:
    n_linkers, F, group = _cases(seed=6, n_cases=1)[0]
    a = count_rgroup_isomers(group, n_linkers * F, F, groups='AB')
    b = count_rgroup_isomers(group, n_linkers * F, F, groups='BA')
    c = count_rgroup_isomers(group, n_linkers * F, F, groups=['R1', 'R2'])
    assert a == b == c


def test_invalid_groups_are_rejected() -> None:
    n = 8
    shift = [(i + 4) % n for i in range(n)]               # swaps two linkers
    with pytest.raises(ValueError, match="closed"):
        prepare_group([[1, 2, 3, 0, 4, 5, 6, 7]], n, 4)   # 4-cycle without its powers
    with pytest.raises(ValueError, match="splits"):
        prepare_group([[0, 1, 2, 4, 3, 5, 6, 7]], n, 4)   # slot jumps linkers
    with pytest.raises(ValueError, match="bijection"):
        prepare_group([[0, 0, 2, 3, 4, 5, 6, 7]], n, 4)
    assert prepare_group([shift], n, 4).order == 2


def test_invalid_specs_are_rejected() -> None:
    with pytest.raises(ValueError):
        make_spec(2, 2, 'ABC')                            # too many groups
    with pytest.raises(ValueError):
        make_spec(4, 4, linker_patterns={'A': 3})         # counts != linkers
    with pytest.raises(ValueError):
        make_spec(4, 4, linker_patterns={'AB': 2, 'BA': 2})


def test_extxyz_round_trip_keeps_labels(tmp_path) -> None:
    from ase import Atoms
    from ase.io import read

    cage = Atoms('C4X4', positions=np.arange(24, dtype=float).reshape(8, 3))
    anchors = cage[[4, 5, 6, 7]]
    iso = rgroup.RGroupIsomer((1, 0, 2, 0), ('A', 'B'), ('AB',))
    h_pos = anchors.positions - 0.5
    path = rgroup.write_rgroup_isomer_file(cage, anchors, iso, [4, 5, 6, 7], str(tmp_path), h_pos)
    back = read(path)
    assert back.get_chemical_symbols() == ['C'] * 4 + ['X', 'H', 'X', 'H']
    assert back.arrays['rgroup'].tolist() == [0, 0, 0, 0, 1, 0, 2, 0]
    assert back.info['rgroup_labels'] == 'A B'
    assert back.info['r_sites'] == '4:R1 6:R2'
    from cage_isomer_builder.utils.sites import read_isomer
    assert read_isomer(path).info['r_sites'] == {4: 'R1', 6: 'R2'}
    assert iso.to_dict() == {'A': [0], 'B': [2]}


def test_rdkit_export_writes_r_labels() -> None:
    pytest.importorskip('rdkit')
    from ase import Atoms
    from rdkit import Chem

    atoms = Atoms('CXX', positions=[[0, 0, 0], [1.5, 0, 0], [-1.5, 0, 0]])
    atoms.set_array('rgroup', np.array([0, 1, 2]))
    bonds = np.zeros((3, 3))
    bonds[0, 1] = bonds[1, 0] = bonds[0, 2] = bonds[2, 0] = 1
    mol = rgroup.rgroup_atoms_to_rdkit(atoms, bonds)
    block = Chem.MolToMolBlock(mol)
    assert 'R#' in block and 'M  RGP  2' in block
    back = Chem.MolFromMolBlock(block, sanitize=False)
    labels = sorted(a.GetIntProp('_MolFileRLabel') for a in back.GetAtoms()
                    if a.HasProp('_MolFileRLabel'))
    assert labels == [1, 2]


def test_fragments_can_be_given_by_group_name() -> None:
    from ase import Atoms
    from cage_isomer_builder.utils.functionalise import _fragments_by_rgroup

    host = Atoms('CAtAt')
    host.set_array('rgroup', np.array([0, 1, 2]))
    host.info['rgroup_labels'] = 'NH2 OH'
    nh2, oh = Atoms('XNHH'), Atoms('XOH')
    assert _fragments_by_rgroup(host, {'OH': oh, 'NH2': nh2}) == [nh2, oh]
    assert _fragments_by_rgroup(host, {'R2': oh, 'R1': nh2}) == [nh2, oh]
    with pytest.raises(ValueError, match="R2"):
        _fragments_by_rgroup(host, {'NH2': nh2})
    with pytest.raises(ValueError, match="match no R-group"):
        _fragments_by_rgroup(host, {'NH2': nh2, 'OH': oh, 'CH3': nh2})


